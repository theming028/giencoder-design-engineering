def render(name, text):
    """生成 name = ('chunk'\n           'chunk') 形式的**单个字符串**（用 + 拼接）。"""
    chunks = text.split('\n')
    body = "\n    + ".join("u%r" % c for c in chunks)
    return "%s = (\n    %s\n)\n" % (name, body)


