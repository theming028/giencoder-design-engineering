def main() -> int:
    src = PAGE.read_text(encoding="utf-8")
    orig = src
    report = []

    before = {m: src.count(m) for m in STRUCT_MARKERS}

    for item in EDITS:
        label, pat, svg = item[0], item[1], item[2]
        cnt = item[3] if len(item) > 3 else 1
        rx = re.compile(pat, re.S)
        n = len(rx.findall(src))
        if n == 0:
            report.append(f"  ✗ {label}：未匹配（可能已替换或结构变动）")
            continue

        def rep(m, _svg=svg):
            head = m.group(1)
            tail = m.group(2) if m.re.groups >= 2 else ""
            return head + esc(_svg) + tail

        src = rx.sub(rep, src, count=cnt)
        report.append(f"  ✓ {label}：替换 {n} 处中的前 {min(cnt, n)} 处")

    for old, new in CSS_EDITS:
        if old in src:
            src = src.replace(old, new, 1)
            report.append(f"  ✓ CSS：{old.strip()[:48]}…")
        else:
            report.append(f"  ✗ CSS：未匹配 {old.strip()[:48]}…")

    print("\n".join(report))

    left = [f for f in OLD_FINGERPRINTS if f in src]
    miss = [m for m in NEW_MARKERS if m not in src]
    struct = {m: (before[m], src.count(m)) for m in STRUCT_MARKERS if before[m] != src.count(m)}
    print(f"\n自检 · 旧图标残留: {left if left else '无'}")
    print(f"自检 · 新图标缺失: {miss if miss else '无'}")
    print(f"自检 · 结构计数漂移: {struct if struct else '无'}")

    if src == orig:
        print("无改动，退出。")
        return 1
    if left or miss or struct:
        print("❌ 自检未通过，未写入。")
        return 1
    PAGE.write_text(src, encoding="utf-8")
    print(f"\n✅ 已写入 {PAGE.relative_to(ROOT)}（{len(src) - len(orig):+d} 字符）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
